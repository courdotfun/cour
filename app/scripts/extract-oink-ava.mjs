// Extract v8's token-avatar system verbatim into app/public/oink-ava.js.
// Pulls the pig sprite table + generator and the "cast" helpers (dress/body/DEF/
// svg/headSvg/NAMES/dressAvatars) by exact line range, then wraps them in one IIFE
// that dresses `.ava:not(.logo)` exactly like v8 does. CSS already ships in v8.css.
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("C:/Users/Lenovo/cour/design/cour-v8.html", "utf8").split("\n");
const L = (a, b) => src.slice(a - 1, b).join("\n"); // 1-indexed inclusive

// --- pig base (script block at 6780) ---
const SV = L(6781, 6781);      // var SV={...};
const UID = L(6783, 6783);     // var uid=0;
const PIG = L(6784, 6784);     // function pig(k){...}
// --- cast avatar helpers (script block at 7618) ---
const INK = L(7620, 7620);     // var I='#1e1f24';
const DRESS = L(7623, 7634);   // dress + body + hood + shirt
const DEF = L(7641, 7658);     // DEF + cache + uidN + uniq + svg + NAMES + headSvg
const DRESSAVA = L(7717, 7724);// function dressAvatars(root){...}

const out = `// AUTO-GENERATED by app/scripts/extract-oink-ava.mjs — do not edit by hand.
// Verbatim port of design/cour-v8.html's default token-avatar system (the "Oink skin"
// LOOK that v8 applies to every un-logo'd community-token avatar). This is the default
// avatar art, NOT the user-owned Oink Collection (that stays "coming soon"). CSS is in v8.css.
(function () {
  if (window.__oinkAvatarsReady) return;
  // ---- pig sprites + generator (okPigSvg) ----
  ${SV}
  ${UID}
  ${PIG}
  function okPigSvg(k) { return SV[k] ? pig(k) : ""; }
  // ---- cast: default character avatars ----
  ${INK}
  ${DRESS}
  ${DEF}
  ${DRESSAVA}
  function run() { try { dressAvatars(document); } catch (e) {} }
  window.__dressAvatars = run;
  window.__oinkAvatarsReady = true;
  if (document.readyState !== "loading") run();
  else document.addEventListener("DOMContentLoaded", run);
  // re-dress cards added by client navigation / re-render
  try {
    new MutationObserver(function () { run(); }).observe(document.body, { childList: true, subtree: true });
  } catch (e) {}
})();
`;
writeFileSync("C:/Users/Lenovo/cour/app/public/oink-ava.js", out);
console.log("wrote app/public/oink-ava.js (", out.length, "bytes )");
